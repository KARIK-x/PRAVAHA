"""Bikram Sambat <-> Gregorian (A.D.) conversion from a vendored 1:1 day map.

The Bikram Sambat calendar is *administrative*, not astronomical: the Panchang
Samiti rules on borderline dates each year, so any "algorithm" that computes
BS month lengths from a formula is a guess. This module therefore does no date
math at all. It looks dates up in a locally vendored, community-verified 1:1
mapping published by OpenNP (``opennp/nepali-dates``) and refuses to answer
outside the years that mapping actually covers.

Guarantees
----------
* Deterministic and offline. No network access, no third-party HTTP service.
* Explicit coverage limits. ``bs_to_ad`` returns ``None`` outside the mapped
  BS years rather than extrapolating.
* Provenance is carried on every answer, so a resolved calendar record can
  always be traced back to the mapping that produced it.

The vendored table lives at ``data/bs_ad/`` and is regenerated by
:func:`build_mapping` (see ``docs/`` for the exact command). It is third-party
data and is deliberately kept out of the application code.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import Any

__all__ = [
    "BsAdError",
    "BsAdMap",
    "bs_to_ad",
    "ad_to_bs",
    "default_map",
    "build_mapping",
    "validate_mapping",
]


class BsAdError(ValueError):
    """Raised when a BS date is malformed or outside the mapped range."""


#: The mapping is *third-party data*, not application data, so it is anchored to
#: the repository rather than to ``PATHS.data`` (which moves with
#: ``MEGATOOL_DATA_DIR`` and is git-ignored). Regenerating it needs network
#: access; reading it never does.
_REPO_ROOT = Path(__file__).resolve().parent.parent

#: Where the consolidated table is written and read from.
MAP_PATH = _REPO_ROOT / "data" / "bs_ad" / "bs_ad_map.json"

#: Where the raw per-BS-year source files are cached (provenance / rebuild).
RAW_DIR = _REPO_ROOT / "data" / "bs_ad" / "dates"

#: Source repository and path template, recorded for provenance.
SOURCE_URL = "https://github.com/opennp/nepali-dates"
SOURCE_PATH = "dates/<BS year>.json"


@dataclass(frozen=True)
class Conversion:
    """One conversion answer plus the provenance a consumer must keep."""

    value: date | tuple[int, int, int] | None
    source: str
    in_coverage: bool
    note: str = ""


class BsAdMap:
    """A loaded BS<->AD mapping with O(1) lookups in both directions."""

    def __init__(self, payload: dict[str, Any]) -> None:
        self.source = str(payload.get("source", SOURCE_URL))
        self.version = int(payload.get("version", 0))
        self.downloaded_at = str(payload.get("downloaded_at", ""))
        self.provenance = str(payload.get("provenance", ""))
        # bs_year -> {bs_day_of_year(1-based) -> AD ISO string}
        self._bs_to_ad: dict[int, dict[int, str]] = {}
        # bs_year -> [bs_month(1..12) indexed by day-of-year - 1]
        self._bs_month: dict[int, list[int]] = {}
        # bs_year -> [bs_day(1..N) indexed by day-of-year - 1]
        self._bs_day: dict[int, list[int]] = {}
        self._ad_to_bs: dict[str, tuple[int, int, int]] = {}
        self._day_count: dict[int, int] = {}
        # (bs_year, bs_month) pairs whose day numbering is inconsistent in the
        # source. No day in one of them may be resolved: the day-of-year
        # arithmetic that bs_to_ad relies on is not trustworthy there.
        self._anomalous_months: set[tuple[int, int]] = set()

        for year_str, pairs in (payload.get("map") or {}).items():
            year = int(year_str)
            if not pairs:
                continue
            days: dict[int, str] = {}
            months: list[int] = []
            bdays: list[int] = []
            for i, pair in enumerate(pairs):
                ad_iso, bs_iso = pair[0], pair[1]
                by, bm, bd = (int(x) for x in bs_iso.split("-"))
                if by != year:
                    raise BsAdError(f"BS year {by} inside the {year} block")
                days[i + 1] = ad_iso
                months.append(bm)
                bdays.append(bd)
                self._ad_to_bs[ad_iso] = (by, bm, bd)
            self._bs_to_ad[year] = days
            self._bs_month[year] = months
            self._bs_day[year] = bdays
            self._day_count[year] = len(days)
        for year, months in self._bs_month.items():
            days = self._bs_day[year]
            prev = 0
            for i, bm in enumerate(months):
                if bm != prev and days[i] != 1:
                    self._anomalous_months.add((year, bm))
                prev = bm
        self.coverage = dict(payload.get("coverage") or {})

    # ------------------------------------------------------------------ basics
    @property
    def bs_years(self) -> list[int]:
        return sorted(self._bs_to_ad)

    @property
    def first_bs_year(self) -> int | None:
        return self.bs_years[0] if self.bs_years else None

    @property
    def last_bs_year(self) -> int | None:
        return self.bs_years[-1] if self.bs_years else None

    def covers_bs(self, bs_year: int) -> bool:
        return bs_year in self._bs_to_ad

    def covers_ad(self, ad: date) -> bool:
        return ad.isoformat() in self._ad_to_bs

    def days_in_bs_year(self, bs_year: int) -> int:
        return self._day_count.get(bs_year, 0)

    def days_in_bs_month(self, bs_year: int, bs_month: int) -> int:
        """Number of days in one BS month, from the mapping (29/30/31/32)."""
        months = self._bs_month.get(bs_year)
        if months is None or not 1 <= bs_month <= 12:
            return 0
        return sum(1 for m in months if m == bs_month)

    # -------------------------------------------------------------- conversion
    def bs_to_ad(self, bs_year: int, bs_month: int, bs_day: int) -> Conversion:
        """Resolve one BS date to a Gregorian :class:`~datetime.date`.

        Returns ``in_coverage=False`` with a ``None`` value when the date is
        outside the vendored mapping or is not a real day in that BS month.
        """
        try:
            self._check_ymd(bs_year, bs_month, bs_day)
        except BsAdError as exc:
            # A structurally invalid date is not resolvable, but it is not a
            # hard error either: report it so the caller can see the reason.
            return Conversion(None, self.source, False, str(exc))
        if not self.covers_bs(bs_year):
            return Conversion(
                None, self.source, False,
                f"BS {bs_year} is outside the mapped range "
                f"{self.first_bs_year}-{self.last_bs_year}",
            )
        if not 1 <= bs_month <= 12:
            return Conversion(None, self.source, False, "BS month out of range 1-12")
        if (bs_year, bs_month) in self._anomalous_months:
            return Conversion(
                None, self.source, False,
                f"BS {bs_year}-{bs_month:02d} has inconsistent day numbering in the "
                f"source mapping; no day in it is resolved rather than guessed",
            )
        dim = self.days_in_bs_month(bs_year, bs_month)
        if dim == 0 or not 1 <= bs_day <= dim:
            return Conversion(
                None, self.source, False,
                f"BS {bs_year}-{bs_month:02d} has {dim} days; day {bs_day} does not exist",
            )
        doy = self._bs_month_start_doy(bs_year, bs_month) + bs_day - 1
        ad = self._bs_to_ad[bs_year][doy]
        return Conversion(date.fromisoformat(ad), self.source, True,
                          "resolved from the vendored 1:1 mapping")

    def ad_to_bs(self, ad: date) -> Conversion:
        """Resolve one Gregorian date to a ``(bs_year, bs_month, bs_day)``."""
        key = ad.isoformat()
        hit = self._ad_to_bs.get(key)
        if hit is not None:
            return Conversion(hit, self.source, True,
                              "resolved from the vendored 1:1 mapping")
        return Conversion(None, self.source, False,
                          f"{key} is outside the mapped range")

    # ------------------------------------------------------------------ helpers
    @staticmethod
    def _check_ymd(y: int, m: int, d: int) -> None:
        if not all(isinstance(v, int) for v in (y, m, d)):
            raise BsAdError("BS year, month and day must all be integers")
        if y < 1:
            raise BsAdError(f"BS year {y} is not a positive integer")
        if not 1 <= m <= 12:
            raise BsAdError(f"BS month {m} is out of range 1-12")
        if d < 1:
            raise BsAdError(f"BS day {d} is out of range")

    def _bs_month_start_doy(self, bs_year: int, bs_month: int) -> int:
        """Day-of-year (1-based) of the first day of a BS month."""
        months = self._bs_month.get(bs_year, [])
        for i, m in enumerate(months):
            if m == bs_month:
                return i + 1
        raise BsAdError(f"BS {bs_year}-{bs_month:02d} not present in the mapping")

    # --------------------------------------------------------------- anomalies
    def month_start_anomalies(self) -> list[str]:
        """BS months in the source whose first mapped day is not day 1.

        The published mapping contains a handful of these (all in BS 2083, the
        current year). They are reported verbatim rather than repaired: silently
        renumbering a third-party dataset would make the provenance untraceable.
        """
        out: list[str] = []
        for year, months in sorted(self._bs_month.items()):
            prev = 0
            for i, bm in enumerate(months):
                if bm != prev and self._bs_day[year][i] != 1:
                    out.append(
                        f"BS {year}-{bm:02d} starts on BS day {self._bs_day[year][i]}"
                    )
                prev = bm
        return out

    def anomalous_bs_dates(self) -> set[tuple[int, int, int]]:
        """BS triples present in the source that :meth:`bs_to_ad` cannot resolve.

        Every day of an anomalous month: the month's own numbering is
        inconsistent, so none of its days can be reached reliably. They are
        returned so consumers can exclude them from round-trip and coverage
        claims rather than being surprised by them.
        """
        out: set[tuple[int, int, int]] = set()
        for (year, bm) in self._anomalous_months:
            months = self._bs_month[year]
            days = self._bs_day[year]
            out.update((year, bm, d) for d, m in zip(days, months, strict=True) if m == bm)
        return out

    # --------------------------------------------------------------- validation
    def validate(self) -> dict[str, Any]:
        """Structural check: contiguity, month lengths, round-trip, coverage."""
        errors: list[str] = []
        anomalies: list[str] = self.month_start_anomalies()
        anomalous_dates = self.anomalous_bs_dates()
        month_lengths: dict[int, list[int]] = {}
        roundtrip_failures = 0
        checked = 0

        for year, days in sorted(self._bs_to_ad.items()):
            ads = [date.fromisoformat(days[k]) for k in sorted(days)]
            # 1. contiguous AD days
            for a, b in zip(ads, ads[1:], strict=False):
                if (b - a).days != 1:
                    errors.append(f"BS {year}: gap between {a} and {b}")
            # 2. round-trip every day. BS day numbers must restart each month;
            #    a month that does NOT is a source-data anomaly (see below), not
            #    a defect in this module, so it is reported separately.
            prev_month = 0
            for doy in sorted(days):
                ad = date.fromisoformat(days[doy])
                back = self._ad_to_bs.get(ad.isoformat())
                checked += 1
                if back is None or back[0] != year:
                    roundtrip_failures += 1
                    continue
                bm, bd = back[1], back[2]
                if (year, bm, bd) in anomalous_dates:
                    # A documented source anomaly: counted below, not a code bug.
                    continue
                if bm != prev_month:
                    prev_month = bm
                if not 1 <= bd <= 32:
                    errors.append(f"BS {year} doy {doy}: impossible BS day {bd}")
            # 3. month lengths for this year
            lengths = []
            for m in range(1, 13):
                n = self.days_in_bs_month(year, m)
                if n == 0:
                    errors.append(f"BS {year}-{m:02d}: missing from the mapping")
                    continue
                if not 29 <= n <= 32:
                    errors.append(f"BS {year}-{m:02d}: impossible length {n}")
                lengths.append(n)
            month_lengths[year] = lengths

        # 4. BS days the mapping never assigns (a real coverage gap)
        missing_bs_days = 0
        for year, months in self._bs_month.items():
            present = {(bm, bd) for bm, bd in zip(months, self._bs_day[year], strict=True)}
            for bm in range(1, 13):
                for bd in range(1, self.days_in_bs_month(year, bm) + 1):
                    if (bm, bd) not in present:
                        missing_bs_days += 1

        # 5. coverage must be a single contiguous BS year range
        years = self.bs_years
        if years and years != list(range(years[0], years[-1] + 1)):
            errors.append("mapped BS years are not contiguous")

        return {
            "ok": not errors and roundtrip_failures == 0,
            "errors": errors,
            "roundtrip_failures": roundtrip_failures,
            "month_start_anomalies": anomalies,
            "anomalous_bs_dates": len(anomalous_dates),
            "missing_bs_days": missing_bs_days,
            "days_checked": checked,
            "bs_years": [years[0], years[-1]] if years else [],
            "month_lengths": month_lengths,
            "source": self.source,
            "first_ad": self.coverage.get("first_ad"),
            "last_ad": self.coverage.get("last_ad"),
        }


def default_map(path: Any = None) -> BsAdMap:
    """Load the vendored mapping. Raises :class:`BsAdError` if it is missing."""
    p = Path(path) if path else MAP_PATH
    if not p.is_file():
        raise BsAdError(
            f"no BS<->AD mapping at {p}. Build it with "
            "`python -m megatool.bs_ad --build` (see docs/)."
        )
    return BsAdMap(json.loads(p.read_text(encoding="utf-8")))


def bs_to_ad(bs_year: int, bs_month: int, bs_day: int,
             mapping: BsAdMap | None = None) -> date | None:
    """Convenience wrapper: resolve a BS date, or ``None`` if unmappable."""
    m = mapping or default_map()
    out = m.bs_to_ad(bs_year, bs_month, bs_day)
    return out.value if out.in_coverage else None


def ad_to_bs(ad: date, mapping: BsAdMap | None = None) -> tuple[int, int, int] | None:
    """Convenience wrapper: resolve a Gregorian date, or ``None``."""
    m = mapping or default_map()
    out = m.ad_to_bs(ad)
    return out.value if out.in_coverage else None


def build_mapping(out_dir: Any = None, raw_dir: Any = None,
                  first_year: int = 2050, last_year: int = 2086,
                  base_url: str = "https://raw.githubusercontent.com/opennp/nepali-dates/main/dates",
                  ) -> dict[str, Any]:
    """Download the OpenNP per-BS-year files and write the consolidated table.

    This is the documented regeneration command. It writes raw per-year files
    (provenance) plus one compact consolidated ``bs_ad_map.json`` holding both
    directions of every mapping.
    """
    import time
    import urllib.request

    out = Path(out_dir) if out_dir else MAP_PATH.parent
    raw = Path(raw_dir) if raw_dir else RAW_DIR
    raw.mkdir(parents=True, exist_ok=True)

    fetched: dict[str, list[list[str]]] = {}
    failures: list[str] = []
    for year in range(first_year, last_year + 1):
        dest = raw / f"{year}.json"
        if dest.is_file():
            rows = json.loads(dest.read_text(encoding="utf-8"))
            fetched[str(year)] = [[r["english_date"], r["nepali_date"]] for r in rows]
            continue
        url = f"{base_url}/{year}.json"
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "PRAVAHA-bs-ad/0.1"})
            with urllib.request.urlopen(req, timeout=30) as resp:  # noqa: S310 - fixed https URL
                rows = json.loads(resp.read().decode("utf-8"))
            if not isinstance(rows, list) or not rows:
                raise BsAdError(f"{url} returned no mappings")
            dest.write_text(json.dumps(rows, ensure_ascii=False), encoding="utf-8")
            fetched[str(year)] = [[r["english_date"], r["nepali_date"]] for r in rows]
        except Exception as exc:  # noqa: BLE001 - recorded, not swallowed
            failures.append(f"{year}: {exc}")
        time.sleep(0.4)

    if not fetched:
        raise BsAdError(f"could not fetch any mapping years: {failures[:3]}")

    years = sorted(fetched)
    coverage = {
        "first_bs": f"{years[0]}-01-01",
        "last_bs": f"{years[-1]}-12-30",
        "first_ad": fetched[years[0]][0][0],
        "last_ad": fetched[years[-1]][-1][0],
        "mappings": sum(len(v) for v in fetched.values()),
    }
    payload = {
        "version": 1,
        "source": SOURCE_URL,
        "source_path": SOURCE_PATH,
        "provenance": (
            "Community-verified 1:1 Bikram Sambat to Gregorian day mapping published by "
            "OpenNP. Each entry maps one Gregorian date to one BS date. The BS calendar "
            "is administrative (Panchang Samiti rulings), so this is a lookup table, not "
            "an algorithm. Vendored locally; no network access is needed at runtime."
        ),
        "downloaded_at": date.today().isoformat(),
        "bs_years": [int(y) for y in years],
        "coverage": coverage,
        "map": fetched,
    }
    out.mkdir(parents=True, exist_ok=True)
    dest = out / "bs_ad_map.json"
    dest.write_text(json.dumps(payload, ensure_ascii=False, separators=(",", ":")),
                    encoding="utf-8")
    return {
        "path": str(dest),
        "bytes": dest.stat().st_size,
        "years": len(fetched),
        "failures": failures,
        "coverage": coverage,
    }


def validate_mapping(path: Any = None) -> dict[str, Any]:
    """Load and structurally validate the vendored mapping."""
    return default_map(path).validate()
